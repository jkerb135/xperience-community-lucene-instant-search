// Generates the three test/section-*.html documents from themes/fixtures/*.html.
// Each section is its own document so the three stylesheet combinations are genuinely isolated
// (spec §6 "Verification"). Run: npm run build:test  —  npm run check passes --check, which
// fails if the committed sections have drifted from the fixtures.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const themes = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');

const ORDER = [
  'search-box', 'suggestions', 'result-stats', 'sort-select', 'results', 'facet-list',
  'toggle-filter', 'active-filters', 'clear-filters', 'filter-sort', 'pagination',
  'range-filter', 'category-tree', 'load-more', 'utilities', 'mount', 'editor-preview',
];

const SECTIONS = {
  'section-shell.html': {
    title: '(a) shell.css only',
    links: ['<link rel="stylesheet" href="../src/shell.css">'],
    note: 'Structure only. No colours, no fonts, no borders — the host page supplies all of that.',
  },
  'section-default.html': {
    title: '(b) shell.css + default.css',
    links: ['<link rel="stylesheet" href="../src/shell.css">', '<link rel="stylesheet" href="../src/default.css">'],
    note: 'The opt-in theme. Every value comes from a --xps-* custom property.',
  },
  'section-clashing.html': {
    title: '(c) shell.css + a hostile host stylesheet',
    links: ['<link rel="stylesheet" href="../src/shell.css">', '<link rel="stylesheet" href="clashing-host.css">'],
    note: 'The host sheet loads last and fights dirty (!important colours, global element rules, content-box). The widgets must stay usable and the host sample below must stay untouched.',
  },
};

const names = readdirSync(join(themes, 'fixtures')).filter((f) => f.endsWith('.html')).map((f) => f.replace(/\.html$/, ''));
const missing = names.filter((n) => !ORDER.includes(n));
if (missing.length) throw new Error(`fixtures not listed in ORDER: ${missing.join(', ')}`);

const fixtures = ORDER.map((n) => ({ n, html: readFileSync(join(themes, 'fixtures', `${n}.html`), 'utf8').trimEnd() }));

const hostSample = `
    <section class="host-sample">
      <h2>Host page sample — outside every .xps element</h2>
      <p>This block must look identical in all three sections. If a widget stylesheet leaks, it changes here first.</p>
      <ul><li>A host list item</li><li>Another host list item</li></ul>
      <p><a href="#">A host link</a> and a host <mark>mark</mark>.</p>
      <p><button type="button">A host button</button> <input type="text" value="A host input"> <select><option>A host select</option></select></p>
    </section>`;

for (const [file, { title, links, note }] of Object.entries(SECTIONS)) {
  const body = fixtures
    .map(({ n, html }) => `    <section class="fx fx--${n}">\n      <h2>${n}</h2>\n${html.replace(/^/gm, '      ')}\n    </section>`)
    .join('\n\n');

  const doc = `<!doctype html>
<!-- GENERATED by themes/scripts/build-test-page.mjs — edit the fixtures, then run npm run build:test -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>xperience-search — ${title}</title>
  <link rel="stylesheet" href="page.css">
  ${links.join('\n  ')}
</head>
<body>
  <main>
    <h1>${title}</h1>
    <p class="note">${note}</p>
${hostSample}

${body}
${hostSample}
  </main>
</body>
</html>
`;

  const path = join(themes, 'test', file);
  if (checkOnly) {
    // compare line-ending-insensitively: git may have checked the file out with CRLF
    const current = (() => { try { return readFileSync(path, 'utf8').replace(/\r\n/g, '\n'); } catch { return null; } })();
    if (current !== doc) {
      console.error(`test/${file} is out of date — run: npm run build:test`);
      process.exit(1);
    }
  } else {
    writeFileSync(path, doc);
    console.log(`wrote test/${file} (${fixtures.length} fixtures)`);
  }
}

if (checkOnly) console.log(`        test/section-*.html match the ${fixtures.length} fixtures`);
