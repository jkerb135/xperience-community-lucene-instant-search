// Generates the C# and TypeScript contract types from the two schemas in contract/:
// xpsearch-api.schema.json (the query API) and xpsearch-ingestion.schema.json (the ingestion API).
//   node scripts/contract.mjs            regenerate in place  (npm run contract:gen)
//   node scripts/contract.mjs --check    regenerate into a temp dir and fail on drift (npm run contract:check)
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const clientDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaOf = (name) => resolve(clientDir, `../../contract/${name}`);
// Run quicktype's JS entry point with this node, not the .bin shim: Node 24 refuses to spawn a
// .cmd file without a shell on Windows (EINVAL).
const quicktype = join(clientDir, 'node_modules', 'quicktype', 'dist', 'index.js');

const banner = (comment, schema) => [
  `${comment} <auto-generated>`,
  `${comment}     Generated from contract/${schema} by quicktype. DO NOT EDIT.`,
  `${comment}     Regenerate with: npm run contract:gen  (in src/XpSearch.Client)`,
  `${comment}     CI guard: npm run contract:check`,
  `${comment} </auto-generated>`,
].join('\n');

// XpSearch.Core is a published package, so its public API must be the contract types and nothing
// else. `--features attributes-only` drops quicktype's FromJson/ToJson plumbing; these three edits
// deal with what it still emits as public. Each one throws if its anchor is gone, so a quicktype
// upgrade that changes the output fails the build instead of quietly widening the public surface.
const csharpEdits = [
  {
    why: 'the placeholder top-level type is never sent on the wire',
    from: 'public partial class XpSearchContract',
    to: 'internal partial class XpSearchContract',
  },
  {
    why: 'unused date converter, emitted for every C# target',
    from: 'public class DateOnlyConverter',
    to: 'internal class DateOnlyConverter',
  },
  {
    why: 'unused time converter, emitted for every C# target',
    from: 'public class TimeOnlyConverter',
    to: 'internal class TimeOnlyConverter',
  },
  {
    // A converter that cannot read a wire value throws a bare Exception, which ASP.NET Core would
    // answer with a 500. JsonException is what a malformed body actually is, and what minimal APIs
    // turn into a 400 before the handler ever runs.
    why: 'a bad enum value on the wire is a bad request, not a server fault',
    all: true,
    from: 'throw new Exception("Cannot ',
    to: 'throw new JsonException("Cannot ',
  },
  {
    // quicktype has no data for `additionalProperties: true`, so it falls back to `object`.
    // JsonElement is what System.Text.Json actually puts in there, and what the projection
    // stage builds, so the property is typed as the thing it holds.
    why: 'the open attributes bag is the one place the schema cannot name a value type',
    from: 'public Dictionary<string, object> Attributes { get; set; }',
    to: 'public Dictionary<string, JsonElement> Attributes { get; set; }',
  },
  // attributes-only emits a converter per string enum (mapping "click", "or", "lte", ...) but
  // attaches it to nothing, so a default JsonSerializer would write the enum as 0/1. Attaching
  // each converter to its enum makes every use round-trip the wire strings, options or no
  // options. The pragma is scoped to the enum, not the file: CS1591 (missing XML doc) is
  // otherwise a real signal here, and every other emitted member carries its schema
  // description. JSON Schema has nowhere to describe an individual enum value, so these
  // members cannot be documented.
  ...['EventType { Click, Conversion }', 'FacetOperator { And, Or }', 'NumericOperator { Eq, Gt, Gte, Lt, Lte, Ne }'].map(
    (declaration) => ({
      why: 'attributes-only leaves the enum converter unattached',
      from: `    public enum ${declaration};`,
      to: [
        '#pragma warning disable CS1591 // no way to document an individual enum member from JSON Schema',
        `    [JsonConverter(typeof(${declaration.split(' ')[0]}Converter))]`,
        `    public enum ${declaration};`,
        '#pragma warning restore CS1591',
      ].join('\n'),
    })
  ),
];

// The ingestion schema keeps two deliberately open objects - a pushed document and a patch body
// carry caller-defined attributes - which quicktype drops entirely for C# (TypeScript gets an
// index signature). These edits put the bag back as extension data. Like every edit here they
// throw when their anchor moves, so a quicktype upgrade fails the build rather than silently
// generating a type that cannot carry attributes.
const openBag = (type) => ({
  why: `${type} is an open object; quicktype emits no extension data for additionalProperties: true`,
  from: `    public partial class ${type}\n    {\n`,
  to: [
    `    public partial class ${type}`,
    '    {',
    '        /// <summary>',
    '        /// The caller-defined attributes, validated against the index schema. Every property of',
    '        /// the JSON object other than the ones declared below lands here.',
    '        /// </summary>',
    '        [JsonExtensionData]',
    '        public Dictionary<string, JsonElement> Attributes { get; set; } = new();',
    '',
    '',
  ].join('\n'),
});

const attachEnumConverter = (declaration) => ({
  why: 'attributes-only leaves the enum converter unattached',
  from: `    public enum ${declaration};`,
  to: [
    '#pragma warning disable CS1591 // no way to document an individual enum member from JSON Schema',
    `    [JsonConverter(typeof(${declaration.split(' ')[0]}Converter))]`,
    `    public enum ${declaration};`,
    '#pragma warning restore CS1591',
  ].join('\n'),
});

const ingestionCsharpEdits = [
  {
    why: 'the placeholder top-level type is never sent on the wire',
    from: 'public partial class XpSearchIngestionContract',
    to: 'internal partial class XpSearchIngestionContract',
  },
  {
    why: 'unused date converter, emitted for every C# target',
    from: 'public class DateOnlyConverter',
    to: 'internal class DateOnlyConverter',
  },
  {
    why: 'unused time converter, emitted for every C# target',
    from: 'public class TimeOnlyConverter',
    to: 'internal class TimeOnlyConverter',
  },
  {
    why: 'a bad enum value on the wire is a bad request, not a server fault',
    all: true,
    from: 'throw new Exception("Cannot ',
    to: 'throw new JsonException("Cannot ',
  },
  openBag('PushDocument'),
  openBag('PatchRequest'),
  attachEnumConverter('TypeEnum { Boolean, Date, Number, String, Text, TypeString }'),
  attachEnumConverter('Health { Degraded, Healthy, Unavailable }'),
];

const csharpTarget = (schema, out, namespace, edits) => ({
  name: 'C#',
  out,
  args: [
    '--lang', 'cs', '--framework', 'SystemTextJson', '--csharp-version', '8',
    '--features', 'attributes-only', '--namespace', namespace,
  ],
  // attributes-only emits no file-level directives of its own, so the header supplies them:
  // #nullable enable because the properties carry nullable annotations (CS8669), and CS8618
  // because a required wire field is left uninitialized until the deserializer sets it.
  header: `${banner('//', schema)}\n#nullable enable\n#pragma warning disable CS8618\n`,
  edits,
});

const typeScriptTarget = (schema, out) => ({
  name: 'TypeScript',
  out,
  args: ['--lang', 'ts', '--just-types', '--acronym-style', 'original'],
  header: `${banner('//', schema)}\n`,
  edits: [],
});

// The published surface of each language binding: the wire types and nothing else. The C# halves
// ship as NuGet packages, so a quicktype upgrade that made its serializer plumbing public would
// silently widen the API; assertPublicSurface is what stops that. The two languages are listed
// separately for the ingestion contract because quicktype names one type differently in each
// (`TypeEnum` in C#, `Type` in TypeScript).
const queryTypes = [
  'EventRequest', 'EventType', 'FacetFilter', 'FacetOperator', 'FacetValue', 'Filters',
  'HighlightOptions', 'NumericFilter', 'NumericOperator', 'RankingInfo', 'Result',
  'SearchRequest', 'SearchResponse', 'SuggestRequest', 'SuggestResponse', 'Suggestion',
];

const ingestionTypes = [
  'BatchDeleteRequest', 'DeleteFilter', 'DeleteResponse', 'DocumentCounts', 'Health',
  'IndexListResponse', 'IndexStatus', 'IndexSummary', 'IngestionError', 'PatchRequest',
  'PushDocument', 'SchemaField', 'UpsertRequest', 'UpsertResponse',
];

const bundles = [
  {
    schema: 'xpsearch-api.schema.json',
    topLevel: 'XpSearchContract',
    publicTypes: { 'C#': queryTypes, TypeScript: queryTypes },
    assert: assertResultShape,
    targets: [
      csharpTarget('xpsearch-api.schema.json', resolve(clientDir, '../XpSearch.Core/Contract/Generated/XpSearchContract.g.cs'), 'XpSearch.Core.Contract', csharpEdits),
      typeScriptTarget('xpsearch-api.schema.json', resolve(clientDir, 'src/contract/generated.ts')),
    ],
  },
  {
    schema: 'xpsearch-ingestion.schema.json',
    topLevel: 'XpSearchIngestionContract',
    publicTypes: {
      'C#': [...ingestionTypes, 'TypeEnum'].sort(),
      TypeScript: [...ingestionTypes, 'Type'].sort(),
    },
    assert: assertOpenDocument,
    targets: [
      csharpTarget('xpsearch-ingestion.schema.json', resolve(clientDir, '../XpSearch.Ingestion/Contract/Generated/XpSearchIngestionContract.g.cs'), 'XpSearch.Ingestion.Contract', ingestionCsharpEdits),
      typeScriptTarget('xpsearch-ingestion.schema.json', resolve(clientDir, 'src/contract/ingestion-generated.ts')),
    ],
  },
];

function generate(bundle, target, outFile) {
  execFileSync(process.execPath, [
    quicktype,
    '--src-lang', 'schema', '--src', schemaOf(bundle.schema),
    '--top-level', bundle.topLevel, ...target.args, '-o', outFile,
  ], { cwd: clientDir, stdio: ['ignore', 'inherit', 'inherit'] });
  let text = readFileSync(outFile, 'utf8').replace(/\r\n/g, '\n');
  for (const edit of target.edits) {
    if (!text.includes(edit.from)) {
      throw new Error(`${target.name}: quicktype no longer emits \`${edit.from}\` (edit reason: ${edit.why}). Review the generated output before removing this edit.`);
    }
    text = edit.all ? text.replaceAll(edit.from, edit.to) : text.replace(edit.from, edit.to);
  }
  return target.header + text;
}

/** The body of one generated type: everything from its declaration to the closing brace. */
function bodyOf(lang, text, type) {
  const anchor = lang === 'C#' ? `public partial class ${type}\n` : `export interface ${type} {`;
  return text.slice(text.indexOf(anchor)).split('\n    }')[0].split('\n}')[0];
}

/**
 * The contract's `Result` is closed - `id`, `score`, `attributes`, `highlights`, `ranking` and
 * nothing else (ADR-0010) - and `attributes` is the single open object inside it. Both halves
 * are asserted here because a schema edit that reopened the result, or closed the attribute
 * bag, would still generate cleanly and only fail much later.
 */
function assertResultShape(bundle, lang, text) {
  const schema = JSON.parse(readFileSync(schemaOf(bundle.schema), 'utf8'));
  const expected = Object.keys(schema.$defs.Result.properties).sort().join(', ');
  // Scoped to Result, so a property removed from it but still present on another type is caught.
  const body = bodyOf(lang, text, 'Result');
  const declared = lang === 'C#'
    ? [...body.matchAll(/\[JsonPropertyName\("([^"]+)"\)]/g)].map((m) => m[1])
    : [...body.matchAll(/^\s{4}(\w+)\??:/gm)].map((m) => m[1]);
  if (declared.sort().join(', ') !== expected) {
    throw new Error(`${lang}: generated Result declares [${declared.join(', ')}] but the schema's Result.properties are [${expected}].`);
  }
  if (/\[JsonExtensionData]|\[property: string]: unknown;/.test(body)) {
    throw new Error(`${lang}: generated Result is an open object; the contract requires a closed one.`);
  }
  const attributes = lang === 'C#'
    ? 'public Dictionary<string, JsonElement> Attributes'
    : 'attributes: { [key: string]: unknown }';
  if (!body.includes(attributes)) {
    throw new Error(`${lang}: Result.attributes is no longer the open bag (\`${attributes}\` is gone).`);
  }
}

/**
 * The mirror image on the ingestion side: a pushed document and a patch body must stay open, or
 * every attribute a caller sends would be dropped on deserialization without a word.
 */
function assertOpenDocument(bundle, lang, text) {
  for (const type of ['PushDocument', 'PatchRequest']) {
    const body = bodyOf(lang, text, type);
    const open = lang === 'C#' ? '[JsonExtensionData]' : '[property: string]: unknown;';
    if (!body.includes(open)) {
      throw new Error(`${lang}: generated ${type} is a closed object (\`${open}\` is gone); pushed attributes would be silently dropped.`);
    }
  }
}

function assertPublicSurface(bundle, lang, text) {
  const declared = lang === 'C#'
    ? [...text.matchAll(/^\s*public (?:partial class|enum) (\w+)/gm)].map((m) => m[1])
    : [...text.matchAll(/^export (?:interface|type) (\w+)/gm)].map((m) => m[1]);
  // The top-level type is the generator's placeholder: internal in C#, unavoidable in TS.
  const actual = declared.filter((name) => name !== bundle.topLevel).sort().join(', ');
  const expected = bundle.publicTypes[lang].join(', ');
  if (actual !== expected) {
    throw new Error(`${lang} (${bundle.schema}): public contract types are [${actual}] but should be [${expected}].`);
  }
}

const check = process.argv.includes('--check');
const scratch = check ? mkdtempSync(join(tmpdir(), 'xpsearch-contract-')) : null;
let drift = false;

for (const bundle of bundles) {
  for (const target of bundle.targets) {
    const outFile = check ? join(scratch, target.out.split(/[\\/]/).pop()) : target.out;
    if (!check) { mkdirSync(dirname(outFile), { recursive: true }); }
    const text = generate(bundle, target, outFile);
    bundle.assert(bundle, target.name, text);
    assertPublicSurface(bundle, target.name, text);
    if (check) {
      const current = readFileSync(target.out, 'utf8').replace(/\r\n/g, '\n');
      if (current !== text) {
        drift = true;
        const currentLines = current.split('\n');
        const newLines = text.split('\n');
        const i = newLines.findIndex((l, n) => l !== currentLines[n]);
        console.error(`DRIFT in ${target.out}\n  first difference at line ${i + 1}:\n  checked in: ${currentLines[i]}\n  generated : ${newLines[i]}`);
      } else {
        console.log(`up to date: ${target.out}`);
      }
    } else {
      writeFileSync(outFile, text);
      console.log(`wrote: ${outFile}`);
    }
  }
}

if (drift) {
  console.error('\nContract outputs are out of date. Run `npm run contract:gen` and commit the result.');
  process.exit(1);
}
